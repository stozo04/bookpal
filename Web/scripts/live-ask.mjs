import { chromium } from "@playwright/test";
const base = "https://bookpal-web.vercel.app";
const b = await chromium.connectOverCDP("http://127.0.0.1:9222");
const p = await b.contexts()[0].newPage();
await p.setViewportSize({ width: 1200, height: 850 });
await p.goto(base + "/library", { waitUntil: "networkidle" });
await p.getByRole("link", { name: /Accelerando/ }).first().click();
await p.waitForURL(/\/read\//); await p.waitForTimeout(5000);
await p.mouse.move(600, 5); await p.getByRole("button", { name: "Ask" }).click();
const box = p.getByRole("textbox").last();
await box.fill("In one sentence, who is Manfred Macx?");
await box.press("Enter");
const t0 = Date.now();
await p.waitForFunction(() => /Manfred/.test(document.querySelector("[role=dialog], aside, [class*=panel]")?.textContent?.split("Manfred Macx?").pop() ?? ""), null, { timeout: 90000 }).catch(() => {});
await p.waitForTimeout(3000);
const txt = (await p.locator("body").innerText()).replace(/\s+/g, " ");
console.log(`${Math.round((Date.now() - t0) / 1000)}s`, txt.slice(txt.indexOf("who is Manfred")).slice(0, 400));
await p.screenshot({ path: "validation-artifacts/live-ask.png" });
await p.close(); await b.close();
