import { chromium } from "@playwright/test";
const base = "https://bookpal-web.vercel.app";
const ok = (l, c, d = "") => console.log(`${c ? "PASS" : "FAIL"}  ${l}${d ? "  —  " + d : ""}`);
const b = await chromium.connectOverCDP("http://127.0.0.1:9222");
const p = await b.contexts()[0].newPage();
await p.setViewportSize({ width: 1200, height: 850 });
await p.goto(base + "/upload", { waitUntil: "networkidle" });
await p.locator("input[type=file]").setInputFiles("tests/fixtures/hello.txt");
await p.waitForFunction(() => [...document.querySelectorAll("li[data-state]")].some((e) => e.textContent.includes("hello") && ["done", "duplicate", "failed"].includes(e.getAttribute("data-state"))), null, { timeout: 60000 });
const row = (await p.locator("li[data-state]").filter({ hasText: "hello" }).first().innerText()).replace(/\s+/g, " ");
ok("upload via hosted site + backend", /On your shelf|Already on your shelf/.test(row), row);
await p.goto(base + "/library", { waitUntil: "networkidle" });
const card = p.getByText("hello", { exact: false }).first();
ok("book on shelf", await card.count() > 0);
await p.getByRole("link", { name: /hello/i }).first().click();
await p.waitForURL(/\/read\//, { timeout: 20000 });
await p.waitForTimeout(2500);
ok("text reader opens", (await p.locator("body").innerText()).length > 20, p.url().replace(base, ""));
await p.goto(base + "/library", { waitUntil: "networkidle" });
await p.getByRole("button", { name: /Options for hello/i }).first().click();
await p.getByRole("menuitem", { name: "Remove from library" }).click();
const dlg = p.locator("dialog[open]");
ok("dialog is for hello", /hello/i.test(await dlg.innerText()) && !/Accelerando/.test(await dlg.innerText()));
await dlg.getByLabel(/Type DELETE/).fill("DELETE");
await dlg.getByRole("button", { name: "Remove", exact: true }).click();
await p.waitForTimeout(3000);
await p.reload({ waitUntil: "networkidle" });
ok("removed again", (await p.getByRole("link", { name: /hello/i }).count()) === 0);
ok("Accelerando still there", (await p.getByText("Accelerando").count()) > 0);
await p.close(); await b.close();
